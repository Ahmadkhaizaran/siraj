import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const req=createRequire(import.meta.resolve('wrangler/package.json'));
await req('esbuild').build({entryPoints:['lib/initial-memory.ts'],bundle:true,format:'esm',platform:'node',outfile:'outputs/initial-memory-unit.mjs'});
const {INITIAL_JUZ,toggleInitialMemory,selectionCount,parseInitialMemory}=await import('../outputs/initial-memory-unit.mjs');
let value=toggleInitialMemory([],INITIAL_JUZ[29].segments,true);
assert.equal(value[0].surah,78);assert.equal(value.at(-1).surah,114);assert.equal(value.length,37);
assert.deepEqual(selectionCount(value,INITIAL_JUZ[29].segments),{selected:564,total:564});
value=toggleInitialMemory(value,[INITIAL_JUZ[29].segments[0]],false);
assert.equal(selectionCount(value,INITIAL_JUZ[29].segments).selected,524);
let first=toggleInitialMemory([],INITIAL_JUZ[0].segments,true);
assert.deepEqual(first.find(m=>m.surah===2).ranges,[[1,141]]);
first=toggleInitialMemory(first,INITIAL_JUZ[1].segments,true);
assert.deepEqual(first.find(m=>m.surah===2).ranges,[[1,252]]);
first=toggleInitialMemory(first,INITIAL_JUZ[0].segments,false);
assert.deepEqual(first.find(m=>m.surah===2).ranges,[[142,252]]);
let all=[];for(const j of INITIAL_JUZ)all=toggleInitialMemory(all,j.segments,true);
assert.equal(all.length,114);assert.equal(all.reduce((n,m)=>n+m.ranges.reduce((a,[x,y])=>a+y-x+1,0),0),6236);
assert.equal(parseInitialMemory(all).length,114);
assert.throws(()=>parseInitialMemory([{surah:1,ranges:[[1,8]]}]));
assert.throws(()=>parseInitialMemory([{surah:1,ranges:[[1,7]]},{surah:1,ranges:[[1,7]]}]));
assert.throws(()=>parseInitialMemory([{surah:115,ranges:[[1,7]]}]));
console.log('PASS: Juz Amma, partial selections, cross-juz surahs, all 6236 verses and input validation');
