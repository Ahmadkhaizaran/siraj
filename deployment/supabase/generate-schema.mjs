// Generate a fresh PostgreSQL schema from Siraj's current Drizzle snapshot.
// This is an initial migration, not an incremental production upgrade.
import { readFileSync, writeFileSync } from 'node:fs';
const snapshot = JSON.parse(readFileSync(new URL('../../drizzle/meta/0008_snapshot.json', import.meta.url)));
const quote = value => `"${value.replaceAll('"', '""')}"`;
const table = name => `siraj.${quote(name)}`;
const lines = [
  '-- Siraj initial PostgreSQL schema, generated from Drizzle snapshot 0008.',
  '-- No account records, passwords or runtime secrets. Apply once to a fresh siraj schema.',
  'CREATE SCHEMA siraj;',
  'REVOKE ALL ON SCHEMA siraj FROM PUBLIC, anon, authenticated;',
];
for (const t of Object.values(snapshot.tables)) {
  const columns = Object.values(t.columns).map(c => {
    if (!['text', 'integer'].includes(c.type)) throw new Error(`Unsupported column type: ${c.type}`);
    return `  ${quote(c.name)} ${c.type === 'integer' ? 'bigint' : 'text'}`
      + (c.autoincrement ? ' GENERATED BY DEFAULT AS IDENTITY' : '')
      + (c.primaryKey ? ' PRIMARY KEY' : '')
      + (c.notNull ? ' NOT NULL' : '')
      + (c.default !== undefined ? ` DEFAULT ${c.default}` : '');
  });
  lines.push(`CREATE TABLE ${table(t.name)} (\n${columns.join(',\n')}\n);`);
  for (const i of Object.values(t.indexes)) {
    lines.push(`CREATE ${i.isUnique ? 'UNIQUE ' : ''}INDEX ${quote(i.name)} ON ${table(t.name)} (${i.columns.map(quote).join(', ')});`);
  }
  lines.push(`ALTER TABLE ${table(t.name)} ENABLE ROW LEVEL SECURITY;`);
}
for (const t of Object.values(snapshot.tables)) {
  for (const f of Object.values(t.foreignKeys)) {
    lines.push(`ALTER TABLE ${table(t.name)} ADD FOREIGN KEY (${f.columnsFrom.map(quote).join(', ')}) REFERENCES ${table(f.tableTo)} (${f.columnsTo.map(quote).join(', ')}) ON DELETE ${f.onDelete} ON UPDATE ${f.onUpdate};`);
  }
}
lines.push(
  'REVOKE ALL ON ALL TABLES IN SCHEMA siraj FROM PUBLIC, anon, authenticated;',
  'REVOKE ALL ON ALL SEQUENCES IN SCHEMA siraj FROM PUBLIC, anon, authenticated;',
  'GRANT USAGE ON SCHEMA siraj TO service_role;',
  'GRANT ALL ON ALL TABLES IN SCHEMA siraj TO service_role;',
  'GRANT ALL ON ALL SEQUENCES IN SCHEMA siraj TO service_role;',
  'ALTER DEFAULT PRIVILEGES IN SCHEMA siraj REVOKE ALL ON TABLES FROM PUBLIC, anon, authenticated;',
);
writeFileSync(new URL('./001_siraj_schema.sql', import.meta.url), lines.join('\n\n') + '\n');
console.log(`Generated ${Object.keys(snapshot.tables).length} tables.`);
